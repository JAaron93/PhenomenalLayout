"""Deployment validation tests for the GCP Document Translation stack.

These tests ensure minimal configuration is present and that optional
system dependencies are documented. They do not reach external networks.
"""

from __future__ import annotations

from pathlib import Path


def test_minimum_dependency_pins_present() -> None:
    req_path = Path("requirements.txt")
    assert req_path.exists(), "requirements.txt must exist and list minimum pins"
    req = req_path.read_text(encoding="utf-8")
    import re

    def assert_version_pin(package: str) -> None:
        pattern = re.compile(
            rf"(?im)^\s*{re.escape(package)}\s*(?:>=|==)\s*[\d.]+"
        )
        assert pattern.search(
            req
        ), (
            f"{package} must be pinned with a minimum or exact version "
            f"(e.g., '{package}>=X.Y.Z' or '{package}==X.Y.Z')"
        )

    # Runtime critical dependencies must be pinned
    for pkg in ("google-cloud-translate", "google-cloud-storage", "fastapi", "pypdf"):
        assert_version_pin(pkg)

    # Legacy rasterization and UI dependencies must NOT be in runtime requirements.txt.
    # Match the package name as a whole word regardless of version operator so that
    # bare names, extras, and any PEP 440 specifier (>=, ==, ~=, !=, <, >) are caught.
    for retired_pkg in ("pdf2image", "Pillow", "pillow", "reportlab", "gradio"):
        pattern = re.compile(rf"(?im)^\s*{re.escape(retired_pkg)}\b")
        assert not pattern.search(
            req
        ), f"{retired_pkg} must not be present in runtime requirements.txt"

    # reportlab must also be absent from requirements-dev.txt (fully eradicated — PR #147)
    # Pillow was its transitive dependent; removing reportlab eliminates Pillow entirely.
    # The pattern matches any form: bare name, extras, or any PEP 440 version specifier.
    dev_req_path = Path("requirements-dev.txt")
    if dev_req_path.exists():
        dev_req = dev_req_path.read_text(encoding="utf-8")
        dev_pattern = re.compile(r"(?im)^\s*reportlab\b")
        assert not dev_pattern.search(dev_req), (
            "reportlab must not be present in requirements-dev.txt — "
            "use build_test_pdf() from tests/conftest.py for PDF test fixtures (PR #147)"
        )


def test_dev_manifest_is_compiled_closure() -> None:
    """Every manifest handed to pip-sync must be a fully compiled closure.

    pip-sync's desired state is exactly the set of explicit pins in the
    files passed to it: its diff uninstalls every installed distribution
    that is not itself an explicit pin (only pip/pip-tools' own dependency
    trees are exempt). A hand-written manifest therefore orphans its
    transitive dependencies — they are uninstalled whenever present and
    silently restored by the install step's dependency resolution when a
    top-level pin is missing, an oscillation whose stable fixed point is a
    broken environment (observed: pytest unrunnable after two syncs).
    requirements-dev.txt must be a uv-compiled closure generated from
    requirements-dev.in, constrained by requirements.txt so transitive
    pins shared with the runtime tier stay merge-consistent.
    """
    import re

    in_path = Path("requirements-dev.in")
    assert in_path.exists(), (
        "requirements-dev.in must exist as the hand-written source "
        "manifest for the development tier"
    )
    dev_in = in_path.read_text(encoding="utf-8")
    for pkg in ("pytest", "mypy", "ruff", "pip-tools"):
        assert re.search(rf"(?m)^\s*{re.escape(pkg)}==", dev_in), (
            f"{pkg} must be pinned in requirements-dev.in — the .in file "
            f"is the source of truth for the compiled dev closure"
        )

    txt_path = Path("requirements-dev.txt")
    assert txt_path.exists(), "requirements-dev.txt must exist"
    dev_txt = txt_path.read_text(encoding="utf-8")
    lines = dev_txt.splitlines()
    assert lines and "autogenerated by uv" in lines[0].lower(), (
        "requirements-dev.txt must be a uv-compiled closure (autogenerated "
        "header) — a hand-written manifest orphans its transitive "
        "dependencies under pip-sync and oscillates the environment"
    )
    assert any("requirements-dev.in" in line for line in lines[:2]), (
        "the requirements-dev.txt header must record its source manifest "
        "so regeneration is discoverable"
    )

    # Compiled-closure invariant: every requirement line is an exact pin.
    requirement_lines = [
        line.strip()
        for line in lines
        if line.strip() and not line.lstrip().startswith("#")
    ]
    assert requirement_lines, "requirements-dev.txt must contain pins"
    pin_pattern = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*==[^\s;]+(?:\s*;.*)?$")
    unpinned = [line for line in requirement_lines if not pin_pattern.match(line)]
    assert not unpinned, (
        f"requirements-dev.txt must pin every package exactly (==); "
        f"unpinned or ranged lines: {unpinned}"
    )

    script_path = Path("scripts/sync-deps.sh")
    assert script_path.exists(), "scripts/sync-deps.sh must exist"
    script = script_path.read_text(encoding="utf-8")
    assert re.search(
        r"pip-sync\s+requirements\.txt\s+requirements-dev\.txt", script
    ), (
        "sync-deps.sh must sync both compiled closures together — the "
        "runtime and development tiers form one desired state"
    )


def test_compiled_union_covers_dependency_closure() -> None:
    """The union of both compiled manifests must cover the dependency closure.

    pip-sync uninstalls every installed distribution that is not itself an
    explicit pin in the manifests it syncs, so a single missing pin — e.g. a
    transitive dependency dropped from a compiled manifest — reintroduces the
    orphaning oscillation this repository fixed. This walks the installed
    environment's dependency metadata from every pinned package (no network)
    and asserts that each environment-applicable dependency is itself pinned
    in the union of requirements.txt and requirements-dev.txt.
    """
    from importlib.metadata import Distribution, distributions

    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name

    def pinned_names(path: str) -> set[str]:
        manifest = Path(path)
        assert manifest.exists(), f"{path} must exist"
        names: set[str] = set()
        for line in manifest.read_text(encoding="utf-8").splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue
            names.add(canonicalize_name(Requirement(stripped).name))
        return names

    union = pinned_names("requirements.txt") | pinned_names("requirements-dev.txt")

    # pip-sync exempts these regardless of pinning
    # (piptools.sync.PACKAGES_TO_IGNORE).
    ignored = {
        "pip",
        "pip-tools",
        "pip-review",
        "pkg-resources",
        "python",
        "wsgiref",
        "argparse",
    }

    installed: dict[str, Distribution] = {}
    for dist in distributions():
        name = dist.metadata["Name"]
        if name:
            installed[canonicalize_name(name)] = dist

    visited: set[str] = set()
    missing: list[str] = []
    queue: list[str] = [key for key in union if key in installed and key not in ignored]
    while queue:
        key = queue.pop()
        if key in visited:
            continue
        visited.add(key)
        for req_text in installed[key].requires or []:
            req = Requirement(req_text)
            if req.marker is not None and not req.marker.evaluate():
                continue
            dep_key = canonicalize_name(req.name)
            if dep_key in ignored:
                continue
            if dep_key not in union:
                missing.append(f"{key} -> {dep_key} ({req_text})")
            elif dep_key in installed:
                queue.append(dep_key)

    assert not missing, (
        "Compiled manifests must cover the full dependency closure — "
        f"pip-sync would uninstall these unpinned dependencies: {missing}"
    )


